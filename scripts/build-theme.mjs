// Generates React Native friendly theme assets from @kjaniec-dev/design.
// - src/kj-theme.generated.css: :root tokens, dark overrides under prefers-color-scheme, Tailwind v4 @theme bridge
// - src/lib/kj-colors.generated.ts: resolved palettes for places that can't use className (SVG, navigation theme)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pkgDir = join(process.cwd(), 'node_modules/@kjaniec-dev/design');
const theme = readFileSync(join(pkgDir, 'src/theme.css'), 'utf8');
const bridge = readFileSync(join(pkgDir, 'src/tailwind.css'), 'utf8');

const block = (selector) => {
  const start = theme.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`Missing ${selector} in theme.css`);
  const end = theme.indexOf('\n}', start);
  return theme.slice(start + selector.length + 3, end);
};

const rootBody = block(':root').replace(/^\s*color-scheme:.*$/m, '');
const darkBody = block('.dark').replace(/^\s*color-scheme:.*$/m, '');
const themeBlock = bridge.slice(bridge.indexOf('@theme {'));

const css = `/* AUTO-GENERATED by scripts/build-theme.mjs from @kjaniec-dev/design — do not edit */
:root {${rootBody}}

@media (prefers-color-scheme: dark) {
  :root {${darkBody}}
}

${themeBlock}`;
writeFileSync('src/kj-theme.generated.css', css);

const parse = (body) =>
  Object.fromEntries(
    [...body.matchAll(/--kj-([\w-]+):\s*([^;]+);/g)].map(([, k, v]) => [
      k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()),
      v.trim(),
    ]),
  );
const light = parse(rootBody);
const dark = { ...light, ...parse(darkBody) };
const pick = (o) =>
  Object.fromEntries(Object.entries(o).filter(([, v]) => /^(#|rgba?\()/.test(v)));
writeFileSync(
  'src/lib/kj-colors.generated.ts',
  `// AUTO-GENERATED by scripts/build-theme.mjs from @kjaniec-dev/design — do not edit
export const kjColors = ${JSON.stringify({ light: pick(light), dark: pick(dark) }, null, 2)} as const;
export type KjColors = { [K in keyof (typeof kjColors)['light']]: string };
`,
);
console.log('theme generated');
